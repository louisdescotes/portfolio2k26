import { execSync } from "child_process";
import { existsSync, writeFileSync } from "fs";
import { join } from "path";

try {
  execSync("ffmpeg -version", { stdio: "ignore" });
} catch {
  console.log("⚠ ffmpeg not found, skipping blur placeholder generation");
  process.exit(0); // Sort sans erreur, sans toucher au fichier
}

const CRAFTS_DIR = "public/crafts";
const OUTPUT_FILE = "src/app/craft/video.ts";

// Liste de tes vidéos avec leurs métadonnées
const videos = [
  { name: "xp4", tags: ["CSS Only"], colorTag: "white" },
  { name: "xp1", tags: ["Motion"], colorTag: "black" },
  { name: "xp2", tags: ["Motion"], colorTag: "black" },
  { name: "xp3", tags: ["CSS Only"], colorTag: "black" },
];

function generatePoster(videoPath, posterPath) {
  if (existsSync(posterPath)) {
    console.log(`✓ Poster already exists: ${posterPath}`);
    return;
  }
  console.log(`Generating poster: ${posterPath}`);
  execSync(
    `ffmpeg -i ${videoPath} -vframes 1 -q:v 2 ${posterPath} 2>/dev/null`
  );
}

function generateBlurDataURL(posterPath) {
  console.log(`Generating blur placeholder: ${posterPath}`);
  const base64 = execSync(
    `ffmpeg -i ${posterPath} -vf "scale=30:-1" -frames:v 1 -f image2pipe -vcodec png - 2>/dev/null | base64 | tr -d '\\n'`,
    { shell: "/bin/bash" }
  ).toString().trim();
  return `data:image/png;base64,${base64}`;
}

// Génère les posters et blur URLs
const result = videos.map((video) => {
  const videoPath = join(CRAFTS_DIR, `${video.name}.mp4`);
  const posterPath = join(CRAFTS_DIR, `${video.name}-poster.jpg`);

  if (!existsSync(videoPath)) {
    console.warn(`⚠ Video not found, skipping: ${videoPath}`);
    return { ...video, blurDataURL: "" };
  }

  generatePoster(videoPath, posterPath);
  const blurDataURL = generateBlurDataURL(posterPath);

  return { ...video, blurDataURL };
});

// Génère le fichier video.ts
const fileContent = `// ⚠️ Auto-generated by scripts/generate-blur-placeholders.mjs
// Do not edit manually — run \`npm run generate:blur\` or \`npm run build\`

const CraftList = {
${result
  .map(
    (v) =>
      `  ${v.name}: { name: "${v.name}", tags: ${JSON.stringify(v.tags)}, colorTag: "${v.colorTag}", blurDataURL: "${v.blurDataURL}" },`
  )
  .join("\n")}
} as const;

export default CraftList;
`;

writeFileSync(OUTPUT_FILE, fileContent);
console.log(`\n✅ Generated ${OUTPUT_FILE}`);